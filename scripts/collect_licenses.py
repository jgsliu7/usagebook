#!/usr/bin/env python3
"""Collect exact Cargo.lock crate license files and checked-in vendored notices.

Requires Python 3 and Cargo; runs no application code. cargo metadata may download
locked registry sources. Pass --offline to use only the local Cargo cache.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--offline", action="store_true")
parser.add_argument("--check", action="store_true", help="fail if the committed notice is stale")
args = parser.parse_args()
command = ["cargo", "metadata", "--locked", "--format-version", "1"]
if args.offline:
    command.append("--offline")
metadata = json.loads(subprocess.check_output(command, cwd=root))
targets = ("aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-msvc", "x86_64-unknown-linux-gnu")
included = set()
for target in targets:
    tree_cmd = ["cargo", "tree", "--locked", "--target", target, "--edges", "normal,build", "--prefix", "none", "--format", "{p}"]
    if args.offline:
        tree_cmd.append("--offline")
    for line in subprocess.check_output(tree_cmd, cwd=root, text=True).splitlines():
        parts = line.split()
        if len(parts) >= 2:
            included.add((parts[0], parts[1].removeprefix("v")))
packages = sorted((p for p in metadata["packages"] if p.get("source") and (p["name"], p["version"]) in included), key=lambda p: (p["name"], p["version"]))
texts = {}
lines = [
    "# Third-party licenses", "",
    "Generated by `python3 scripts/collect_licenses.py` from the exact versions resolved by Cargo.lock.",
    "Includes enabled default-feature dependencies and build dependencies for macOS arm64/x86_64, Windows x86_64 MSVC and Linux x86_64 GNU; inclusion here does not mean every component is linked into every platform binary.",
    "Crate license texts are copied verbatim from the official crates.io source archives. Bundled JavaScript notices come from the tagged upstream releases linked below.",
    "For alternative licenses (OR), the upstream alternatives are preserved; additional AND notices are included. usagebook itself is Apache-2.0; see LICENSE.", "",
    "## Inventory", "", "| Component | Declared license | Source / license texts |", "|---|---|---|",
]


def register(text):
    digest = hashlib.sha256(text.encode()).hexdigest()[:16]
    texts.setdefault(digest, text)
    return f"[text](#license-{digest})"


for package in packages:
    folder = Path(package["manifest_path"]).parent
    candidates = sorted(p for p in folder.rglob("*") if p.is_file() and p.name.lower().startswith(("license", "copying", "copyright")))
    if package.get("license_file"):
        explicit = folder / package["license_file"]
        if explicit not in candidates:
            candidates.append(explicit)
    if not candidates:
        raise SystemExit(f"Missing license text: {package['name']} {package['version']}")
    refs = []
    for path in candidates:
        text = path.read_text(encoding="utf-8").strip()
        refs.append(f"`{path.relative_to(folder)}` {register(text)}")
    name, version = package["name"], package["version"]
    url = f"https://crates.io/crates/{name}/{version}"
    lines.append(f"| {name} {version} | {package.get('license') or 'See license file'} | [crate]({url}); " + "; ".join(refs) + " |")

vendor = root / "crates/usagebook-cli/src/vendor/licenses"
for name, version, repo, filename in [
    ("Chart.js", "4.4.3", "chartjs/Chart.js", "Chart.js-4.4.3-MIT.txt"),
    ("@kurkle/color", "0.3.2", "kurkle/color", "kurkle-color-0.3.2-MIT.txt"),
]:
    source = f"https://github.com/{repo}/blob/v{version}/LICENSE.md"
    lines.append(f"| {name} {version} | MIT | [tagged upstream]({source}); {register((vendor / filename).read_text().strip())} |")

lines += ["", "## License texts", ""]
for digest, text in texts.items():
    lines += [f'<a id="license-{digest}"></a>', "", f"### License {digest}", "", "````text", text, "````", ""]
output = "\n".join(lines)
path = root / "THIRD_PARTY_LICENSES.md"
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit("THIRD_PARTY_LICENSES.md is stale; run python3 scripts/collect_licenses.py")
else:
    path.write_text(output)
print(f"{len(packages)} crates + 2 vendored JavaScript components; {len(texts)} distinct license texts")
